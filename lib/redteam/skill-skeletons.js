/** 取骨架；没有配骨架的技能返回 null，调用方回退到全文。 */
export function skeletonOf(name) {
  return SKELETONS[String(name || '').trim()] || null
}

/** 渲染成给模型看的紧凑文本。「何时用」由技能目录的 description 承担，这里不重复。 */
export function renderSkeleton(name, sk) {
  if (!sk) return ''
  const lines = ['## ' + name]
  if (sk.signals && sk.signals.length) {
    lines.push('判据：')
    for (const s of sk.signals) lines.push('- ' + s)
  }
  if (sk.stop) lines.push('换路：' + sk.stop)
  if (sk.note) lines.push('注意：' + sk.note)
  return lines.join('\n')
}

export default { SKELETONS, skeletonOf, renderSkeleton }
